// Store a string in a variable.
var message = "I am learning JavaScript!";

// Display the message in a pop-up.
window.alert(message);

// Display the message on the webpage.
document.write(message);

// Use escaped quotation marks inside a string.
var quote = "I'm learning JavaScript, and I said, \"This is fun!\"";
document.write("<br>" + quote);

// Join strings directly inside document.write().
document.write("<br>" + "I am learning " + "JavaScript!");

// Store a concatenated string in a variable and display it.
var sentence = "I am learning " + "JavaScript!";
document.write("<br>" + sentence);

// Declare three variables in one statement.
var family = "The Singhs", dad = "Gagandeep", mom = "Taranjit";

// Display the names on separate lines.
document.write("<br>" + mom);
document.write("<br>" + dad);

// Start a new line and display the result of an expression.
document.write("<br>");
document.write(5 + 3);
// Store the beginning and end of the string in two variables.
var Sent1 = "This is the beginning of the string";
var Sent2 = " and this is the end of the string";

// Concatenate the variables and display the complete string.
document.write("<br>" + Sent1 + Sent2);